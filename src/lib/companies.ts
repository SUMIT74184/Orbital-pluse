export const OTHER_SECTOR: Sector = { key: "other", label: "Other", companies: [] };

const SECTOR_OF = new Map<string, Sector>();
for (const s of SECTORS) for (const c of s.companies) if (!SECTOR_OF.has(c)) SECTOR_OF.set(c, s);

export function sectorOf(company: string): Sector {
  return SECTOR_OF.get(company) ?? OTHER_SECTOR;
}

/**
 * Icon URLs to try in order. Google's service has sharper icons but answers a miss with a 16px globe,
 * so CompanyIcon skips any result that small and moves on to DuckDuckGo, then to a monogram.
 */
export function companyLogos(name: string): string[] {
  const domain = DOMAINS[name];
  if (!domain) return [];
  return [`https://www.google.com/s2/favicons?domain=${domain}&sz=64`, `https://icons.duckduckgo.com/ip3/${domain}.ico`];
}

/** Stable hue per name so a company's monogram looks the same everywhere. */
export function companyHue(name: string): number {
  let h = 0;
  for (const ch of name) h = (h * 31 + ch.charCodeAt(0)) % 360;
  return h;
}

export function companyInitials(name: string): string {
  const words = name.replace(/[^A-Za-z0-9 ]/g, " ").split(/\s+/).filter(Boolean);
  if (words.length === 0) return "?";
  if (words.length === 1) return words[0].slice(0, 2).toUpperCase();
  return (words[0][0] + words[1][0]).toUpperCase();
}
